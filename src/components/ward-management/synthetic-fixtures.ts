export const wardRegions = ["North", "East", "South", "Country"] as const;

export function wardPatientById(id: string) {
  return wardPatients.find((patient) => patient.id === id) ?? wardPatients[0];
}

export function wardHospitalByCode(code: string) {
  return wardHospitals.find((hospital) => hospital.code === code || hospital.code.startsWith(code)) ?? wardHospitals[0];
}

export function operationalPriorityScore(patient: WardPatient) {
  return Math.max(0, Math.min(99, patient.score - patient.urgency * 5 - 9));
}
