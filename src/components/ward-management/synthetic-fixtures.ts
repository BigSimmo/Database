export type WardRole = "flow" | "ed" | "ward";

export type MovementStage =
  "placement_requested" | "destination_review" | "bed_held" | "handover_ready" | "moving" | "arrived";

export type PatientCohort = "Adult" | "Older adult";
export type WardSetting = "Open" | "Secure";

export type WardPatient = {
  id: string;
  urgency: 1 | 2 | 3;
  elapsed: string;
  cohort: PatientCohort;
  setting: WardSetting;
  catchment: "North" | "East" | "South" | "Country";
  voluntaryStatus:
    "Voluntary" | "Referred for psychiatric examination" | "Detained awaiting examination" | "Involuntary inpatient";
  legalDetail: string;
  destinationCode: string;
  destinationName: string;
  stage: MovementStage;
  owner: string;
  score: number;
  referredTo: string;
  referralStatus: string;
  transport: string;
  blocker: string;
  recommendationReasons: string[];
  alternatives: Array<{
    hospitalCode: string;
    hospitalName: string;
    score: number;
    reason: string;
    /** Synthetic transport outlook for this alternative, where one has been modelled. */
    etaLabel?: string;
  }>;
};

export type WardHospital = {
  id: string;
  code: string;
  name: string;
  region: "North" | "East" | "South" | "Country";
  /** WACHS services sit outside the three metropolitan health services. */
  service: "North Metro" | "East Metro" | "South Metro" | "WACHS" | "Private";
  settings: WardSetting[];
  cohorts: PatientCohort[];
  beds: number;
  /** Confirmed empty and allocatable now. */
  available: number;
  /** Reserved for a named movement until a stated expiry. */
  held: number;
  /** A subset of `occupied` expected to free after a named action. Not yet allocatable. */
  potential: number;
  /** Present but unusable, with a reason. */
  blocked: number;
  /** In use. `available + held + blocked + occupied` always equals `beds`. */
  occupied: number;
  lastConfirmed: string;
};

