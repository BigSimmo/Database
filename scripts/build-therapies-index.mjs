// Generates src/data/therapies-index.json — a trimmed, server-importable projection
// of public/therapy-compass-data/therapies.json (~2.5 MB). The full dataset is fetched
// client-side by the interactive Therapy Compass screens; the server only needs a small
// rankable/metadata projection for routing (generateStaticParams / notFound / metadata)
// and the universal-search "therapies" domain. Re-run after editing the source dataset,
// then run Prettier (which owns the committed file's exact formatting):
//
//   node scripts/build-therapies-index.mjs && npm run format
//
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { escapeFalseOpenAiKeySignatures } from "./lib/escape-false-openai-key-signatures.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const publicData = join(root, "public", "therapy-compass-data");
const serverTarget = join(root, "src", "data", "therapies-index.json");
const browserTarget = join(publicData, "therapies-index.json");
const manifestTarget = join(root, "src", "components", "therapy-compass", "data", "generated-assets.ts");
const checkOnly = process.argv.includes("--check");
const currentManifest = existsSync(manifestTarget) ? readFileSync(manifestTarget, "utf8") : "";
const currentFullFilename = currentManifest.match(/full: "([^"]+)"/)?.[1];
const source = existsSync(join(publicData, "therapies.json"))
  ? join(publicData, "therapies.json")
  : currentFullFilename
    ? join(publicData, currentFullFilename)
    : join(publicData, "therapies.json");
if (!existsSync(source)) {
  throw new Error(
    `Missing therapy source dataset. Expected ${join(publicData, "therapies.json")} or the manifest full asset.`,
  );
}

const therapies = JSON.parse(readFileSync(source, "utf8"));

/** Content-addressed catalogue assets this generator owns, e.g. `therapies-home.211dab554c4ec62d.json`. */
const HASHED_ASSET_RE = /^therapies(?:-(?:home|index))?\.[a-f0-9]{16}\.json$/;

/** Every hashed catalogue asset currently sitting in `public/therapy-compass-data`. */
function listHashedAssets() {
  return readdirSync(publicData)
    .filter((name) => HASHED_ASSET_RE.test(name))
    .sort();
}

/**
 * Filenames recorded under `name` in a `generated-assets.ts` body, keyed by
 * kind. Keyed rather than positional: a manifest missing one kind must not
 * shift the others into the wrong slot.
 */
function manifestAssets(body, name) {
  const block = body.match(new RegExp(`${name} = \\{([^}]*)\\}`))?.[1] ?? "";
  const entries = ["full", "index", "home"]
    .map((kind) => [kind, block.match(new RegExp(`${kind}: "([^"]+)"`))?.[1]])
    .filter(([, filename]) => Boolean(filename));
  return Object.fromEntries(entries);
}

function renderManifest(current, previous) {
  const entry = (assets) =>
    `{\n  full: "${assets.full}",\n  index: "${assets.index}",\n  home: "${assets.home}",\n} as const;\n`;
  return [
    "// Generated by scripts/build-therapies-index.mjs. Do not edit.",
    `export const THERAPY_CATALOGUE_ASSETS = ${entry(current)}`,
    "// The generation this one replaced. Retained on disk across one content-",
    "// changing regeneration so a client whose bundle still names the previous",
    "// content-addressed URL does not 404 mid-session; older generations are",
    "// pruned. `useTherapyData` also falls back to the unversioned alias for",
    "// bundles that include that fallback (pre-fallback clients are best-effort).",
    `export const THERAPY_CATALOGUE_ASSETS_PREVIOUS = ${entry(previous)}`,
  ].join("\n");
}

// The source catalogue's `modality` is an echo of one of the record's own tags:
// all 205 records carry one, every value is also present in that record's
// `tags`, and the whole catalogue collapses to just CBT/ACT/DBT. That inference
// mislabels somatic and psychodynamic treatments — ECT and rTMS as "ACT",
// Psychoanalysis and Psychodynamic Psychotherapy as "CBT", MBT and TFP as
// "DBT" — and the value renders as a curated chip on the detail and recommend
// screens while scoring related-therapy selection. A guess presented as a
// curated fact is a clinical mislabel, so emit the field only when the source
// genuinely curates a value that is not already one of the record's tags.
// Consumers already treat `null` as "unknown" and render nothing.
function curatedModality(therapy) {
  const value = therapy.modality ?? null;
  if (!value) return null;
  const tags = Array.isArray(therapy.tags) ? therapy.tags : [];
  return tags.includes(value) ? null : value;
}

// Detail and recommend load the full catalogue (`catalogue: "full"`), not the
// index projections. Scrub tag-echo modalities there too; a raw copy of the
// source would leave the mislabel on the only path that renders the chip.
const curatedFull = therapies.map((therapy) => ({
  ...therapy,
  modality: curatedModality(therapy),
}));

const projected = therapies
  .map((t) => ({
    slug: t.slug,
    name: t.name,
    category: t.category ?? null,
    modality: curatedModality(t),
    clinicalSummary: t.clinicalSummary ?? null,
    bestUsedFor: t.bestUsedFor ?? null,
    targetSymptoms: t.targetSymptoms ?? null,
    indications: t.indications ?? null,
    reviewStatus: t.reviewStatus ?? "needs_review",
    patientSheetAvailable: Boolean(t.patientSheetAvailable),
    briefInterventionAvailable: Boolean(t.briefInterventionAvailable),
    tags: Array.isArray(t.tags) ? t.tags : [],
    aliases: Array.isArray(t.aliases) ? t.aliases : [],
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

const browserProjected = therapies
  .map((therapy) => ({
    slug: therapy.slug,
    name: therapy.name,
    category: therapy.category ?? null,
    modality: curatedModality(therapy),
    // The browser index is the browse/pathway payload, not the search corpus.
    // Keep only the short subtitle the catalogue cards render. Search loads the
    // full records so removing long clinical prose here cannot change recall.
    bestUsedFor: therapy.bestUsedFor?.split(/(?<=\.)\s+/)[0] ?? null,
    reviewStatus: therapy.reviewStatus ?? "needs_review",
    patientSheetAvailable: Boolean(therapy.patientSheetAvailable),
    briefInterventionAvailable: Boolean(therapy.briefInterventionAvailable),
    tags: Array.isArray(therapy.tags) ? therapy.tags : [],
    aliases: Array.isArray(therapy.aliases) ? therapy.aliases : [],
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

// The landing page only renders compact list rows. Keep its first-paint payload
// free of search-only prose; search loads the full records separately.
const browserHomeProjected = therapies
  .map((therapy) => ({
    slug: therapy.slug,
    name: therapy.name,
    category: therapy.category ?? null,
    bestUsedFor: therapy.bestUsedFor?.split(/(?<=\.)\s+/)[0] ?? null,
    reviewStatus: therapy.reviewStatus ?? "needs_review",
    patientSheetAvailable: Boolean(therapy.patientSheetAvailable),
    briefInterventionAvailable: Boolean(therapy.briefInterventionAvailable),
    tags: Array.isArray(therapy.tags) ? therapy.tags : [],
    aliases: Array.isArray(therapy.aliases) ? therapy.aliases : [],
  }))
  .sort((a, b) => a.name.localeCompare(b.name));

function syncTarget(target, records) {
  const expected = `${escapeFalseOpenAiKeySignatures(JSON.stringify(records, null, 2))}\n`;
  if (checkOnly) {
    let actual = "";
    try {
      actual = readFileSync(target, "utf8");
    } catch {
      throw new Error(`Missing generated therapy index: ${target}`);
    }
    let parsed;
    try {
      parsed = JSON.parse(actual);
    } catch {
      throw new Error(`Generated therapy index is invalid JSON: ${target}`);
    }
    if (JSON.stringify(parsed) !== JSON.stringify(records)) {
      throw new Error(`Generated therapy index is stale: ${target}`);
    }
    return;
  }
  writeFileSync(target, expected);
  console.log(`Wrote ${records.length} therapy records to ${target}`);
}

/**
 * Full catalogue on disk is compact single-line JSON (no pretty indent, no
 * trailing newline) — that is the historical `therapies.json` shape (~2.5 MB
 * one line). Pretty-printing it turns a modality scrub into a ~36k-line PR
 * churn (alias + hashed twin). Projections stay pretty via `syncTarget`.
 */
function syncFullCatalogue(target, records) {
  const expected = escapeFalseOpenAiKeySignatures(JSON.stringify(records));
  if (checkOnly) {
    let actual = "";
    try {
      actual = readFileSync(target, "utf8");
    } catch {
      throw new Error(`Missing generated therapy catalogue: ${target}`);
    }
    let parsed;
    try {
      parsed = JSON.parse(actual);
    } catch {
      throw new Error(`Generated therapy catalogue is invalid JSON: ${target}`);
    }
    if (JSON.stringify(parsed) !== JSON.stringify(records)) {
      throw new Error(`Generated therapy catalogue is stale: ${target}`);
    }
    if (actual.includes("\n") || actual !== expected) {
      throw new Error(
        `Full therapy catalogue must stay compact single-line JSON (no pretty-print). Re-run \`node scripts/build-therapies-index.mjs\`.`,
      );
    }
    return;
  }
  writeFileSync(target, expected);
  console.log(`Wrote ${records.length} therapy records to ${target} (compact)`);
}

syncTarget(serverTarget, projected);
if (!checkOnly) {
  const browserHomeTarget = join(publicData, "therapies-home.json");
  syncTarget(browserTarget, browserProjected);
  syncTarget(browserHomeTarget, browserHomeProjected);
  const hashedAsset = (target, stem) => {
    const contents = readFileSync(target);
    const hash = createHash("sha256").update(contents).digest("hex").slice(0, 16);
    const filename = `${stem}.${hash}.json`;
    writeFileSync(join(publicData, filename), contents);
    return filename;
  };
  // Keep the unversioned aliases for clients loaded before this deployment.
  // Content-addressed files remain immutable, while an already-open older client
  // can still fetch the URL embedded in its JavaScript bundle after assets swap.
  // Write the curated full catalogue (not a raw source copy): detail/recommend
  // fetch this payload, and tag-echo modalities must not survive on that path.
  // Keep the payload compact — see syncFullCatalogue.
  const legacyFullTarget = join(publicData, "therapies.json");
  syncFullCatalogue(legacyFullTarget, curatedFull);
  const fullFilename = hashedAsset(legacyFullTarget, "therapies");
  const indexFilename = hashedAsset(browserTarget, "therapies-index");
  const homeFilename = hashedAsset(browserHomeTarget, "therapies-home");
  const current = { full: fullFilename, index: indexFilename, home: homeFilename };
  // The generation being replaced stays on disk across one content-changing
  // regeneration. A client loaded before that regeneration has the *previous*
  // hashed URL compiled into its bundle, and pruning it immediately would 404
  // that session the moment it opened a catalogue route — the
  // deployment-straddling failure the unversioned aliases were added to
  // prevent, reintroduced one level down.
  const priorCurrent = manifestAssets(currentManifest, "THERAPY_CATALOGUE_ASSETS");
  const priorPrevious = manifestAssets(currentManifest, "THERAPY_CATALOGUE_ASSETS_PREVIOUS");
  // Rotate the grace window per kind, and only when that kind's content actually
  // changed. Rotating on every invocation would make a second local re-run —
  // routine while iterating — silently retire the generation a client loaded
  // before the last deploy still fetches, which is the whole point of retaining
  // it. A kind absent from the old manifest (first run, hand-edited file) falls
  // back to the new filename so the retained set never names a file that was
  // never written.
  const previous = Object.fromEntries(
    ["full", "index", "home"].map((kind) => {
      const replaced = priorCurrent[kind];
      if (replaced && replaced !== current[kind]) return [kind, replaced];
      return [kind, priorPrevious[kind] ?? current[kind]];
    }),
  );
  writeFileSync(manifestTarget, renderManifest(current, previous));
  // Prune everything older than those two generations. Without this, every data
  // revision strands the previous full catalogue (~2.5 MB) plus both projections
  // in `public/` forever — carried in git history and in every Docker image. PR
  // #1489 stranded two inside a single pull request and needed a hand-deletion
  // commit to clear them. Growth is now bounded at two generations, not N.
  const keep = new Set([...Object.values(current), ...Object.values(previous)]);
  const pruned = listHashedAssets().filter((name) => !keep.has(name));
  for (const name of pruned) rmSync(join(publicData, name));
  console.log(`Wrote content-addressed therapy assets: ${homeFilename}, ${indexFilename}, ${fullFilename}`);
  if (pruned.length > 0) console.log(`Pruned ${pruned.length} superseded asset(s): ${pruned.join(", ")}`);
} else {
  if (!existsSync(manifestTarget)) {
    throw new Error(`Missing generated therapy asset manifest: ${manifestTarget}`);
  }
  const manifest = readFileSync(manifestTarget, "utf8");
  // Only the current generation and the one-deploy grace generation may be
  // committed. This is the gate that would have caught the orphans PR #1489
  // stranded before review did, and it keeps the retained set explicit rather
  // than letting each regeneration quietly add another 2.5 MB to the image.
  const manifested = new Set([
    ...Object.values(manifestAssets(manifest, "THERAPY_CATALOGUE_ASSETS")),
    ...Object.values(manifestAssets(manifest, "THERAPY_CATALOGUE_ASSETS_PREVIOUS")),
  ]);
  const orphaned = listHashedAssets().filter((name) => !manifested.has(name));
  if (orphaned.length > 0) {
    throw new Error(
      `Superseded therapy assets are still committed: ${orphaned.join(", ")}. Re-run \`node scripts/build-therapies-index.mjs\` to prune them.`,
    );
  }
  for (const retained of Object.values(manifestAssets(manifest, "THERAPY_CATALOGUE_ASSETS_PREVIOUS"))) {
    if (!existsSync(join(publicData, retained))) {
      throw new Error(
        `Retained previous-generation therapy asset is missing: ${retained}. Clients loaded before the last deploy fetch this URL.`,
      );
    }
  }
  for (const [kind, records] of [
    ["full", curatedFull],
    ["index", browserProjected],
    ["home", browserHomeProjected],
  ]) {
    const filename = manifest.match(new RegExp(`${kind}: "([^"]+)"`))?.[1];
    if (!filename) throw new Error(`Missing ${kind} therapy asset in ${manifestTarget}`);
    const contents = readFileSync(join(publicData, filename));
    const hash = createHash("sha256").update(contents).digest("hex").slice(0, 16);
    const stem = kind === "full" ? "therapies" : `therapies-${kind}`;
    const legacyFilename = `${stem}.json`;
    if (filename !== `${stem}.${hash}.json` || JSON.stringify(JSON.parse(contents)) !== JSON.stringify(records)) {
      throw new Error(`Generated therapy asset is stale: ${filename}`);
    }
    const legacyContents = readFileSync(join(publicData, legacyFilename));
    if (!legacyContents.equals(contents)) {
      throw new Error(`Therapy compatibility alias is stale: ${legacyFilename}`);
    }
    if (kind === "full") {
      const text = contents.toString("utf8");
      const expected = escapeFalseOpenAiKeySignatures(JSON.stringify(records));
      if (text.includes("\n") || text !== expected) {
        throw new Error(`Full therapy catalogue must stay compact single-line JSON (no pretty-print): ${filename}`);
      }
    }
  }
}
if (checkOnly) console.log(`Therapy indexes are current (${projected.length} records).`);
